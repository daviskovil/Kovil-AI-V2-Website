"""Generate src/data/sitemap-lastmod.ts: last git-commit date per sitemap path.

For each literal `${BASE_URL}/<path>` in src/app/sitemap.ts, take the newest commit touching
src/app/<path>/page.tsx plus the components that page imports from '@/src/...'.
Run after meaningful content changes:  python3 scripts/gen_sitemap_lastmod.py
"""
import re, os, subprocess, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sitemap = open(f'{ROOT}/src/app/sitemap.ts', encoding='utf-8').read()
paths = sorted(p for p in set(re.findall(r"url: `\$\{BASE_URL\}(/[^`]*)`", sitemap)) | {'/'} if '${' not in p)


def resolve(alias):
    base = os.path.join(ROOT, alias.replace('@/', ''))
    for ext in ('.tsx', '.ts', '/index.tsx'):
        if os.path.exists(base + ext):
            return base + ext
    return None


def files_for(path):
    rel = path.strip('/')
    page = os.path.join(ROOT, 'src', 'app', rel, 'page.tsx') if rel else os.path.join(ROOT, 'src', 'app', 'page.tsx')
    out = []
    if os.path.exists(page):
        out.append(page)
        src = open(page, encoding='utf-8').read()
        for m in re.finditer(r"from ['\"](@/src/(?:pages|data|components)/[^'\"]+)['\"]", src):
            f = resolve(m.group(1))
            if f and 'components/ui' not in f.replace(os.sep, '/'):
                out.append(f)
    elif rel.startswith('hire/'):  # /hire/<role> pages are rendered from one data file
        out.append(os.path.join(ROOT, 'src', 'data', 'hire-roles.ts'))
    return out


def last_commit(files):
    if not files:
        return None
    r = subprocess.run(['git', 'log', '-1', '--format=%cI', '--'] + files, cwd=ROOT, capture_output=True, text=True)
    return r.stdout.strip() or None


result, missing = {}, []
for p in paths:
    d = last_commit(files_for(p))
    if d:
        result[p] = d[:10]  # date only: honest granularity
    else:
        missing.append(p)

fallback = max(result.values()) if result else '2026-01-01'
body = ',\n'.join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(result.items()))
open(f'{ROOT}/src/data/sitemap-lastmod.ts', 'w', encoding='utf-8').write(
    "// Generated by scripts/gen_sitemap_lastmod.py from git history. Do not edit by hand.\n"
    f"export const SITEMAP_LASTMOD: Record<string, string> = {{\n{body},\n}}\n\n"
    "// Used for routes without a resolvable source file; deliberately NOT the current time.\n"
    "export const SITEMAP_LASTMOD_FALLBACK = '2026-10-03'\n"
)
print(f'{len(result)} paths dated, {len(missing)} without a source file (use fallback)')
dates = sorted(set(result.values()))
print('distinct dates:', len(dates), '| oldest', dates[0], '| newest', dates[-1])
print('sample:', {k: result[k] for k in list(result)[:4]})
print('missing sample:', missing[:6])
