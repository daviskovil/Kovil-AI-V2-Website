# White circle on a black JPEG background: cut the circle out onto transparency.
CIRCLE_ON_BLACK = {'bigcommerce'}
EXTRA = {'salesforce': os.path.join(ROOT, 'public', 'logo-salesforce.webp')}
MAXD = 360
result, flags = {}, []


def is_filled(im):
    """Opaque, non-white, near-uniform corners => full-bleed colored logo."""
    w, h = im.size
    cs = [im.getpixel(p) for p in [(1, 1), (w - 2, 1), (1, h - 2), (w - 2, h - 2)]]
    if any(c[3] < 250 for c in cs):
        return None
    if min(cs[0][:3]) > 235:
        return None
    if all(sum(abs(a - b) for a, b in zip(cs[0][:3], c[:3])) < 30 for c in cs):
        return cs[0][:3]
    return None


def trim(im):
    px = im.load(); w, h = im.size
    has_alpha = any(im.getpixel(p)[3] < 250 for p in [(1, 1), (w - 2, 1), (1, h - 2), (w - 2, h - 2)])
    if has_alpha:
        bbox = im.getchannel('A').point(lambda a: 255 if a > 20 else 0).getbbox()
    else:
        mask = Image.new('L', im.size, 0); mp = mask.load()
        for y in range(h):
            for x in range(w):
                r, g, b, a = px[x, y]
                if min(r, g, b) < 238:
                    mp[x, y] = 255
        bbox = mask.getbbox()
    return im.crop(bbox) if bbox else im


def light_fraction(im):
    px = [p for p in im.getdata() if p[3] > 200]
    if not px:
        return 0
    return sum(1 for p in px if min(p[:3]) > 232) / len(px)


def handle(slug, path):
    if path.endswith('.svg'):
        shutil.copy(path, os.path.join(OUT, slug + '.svg'))
        vb = re.search(r'viewBox="([^"]+)"', open(path, encoding='utf-8').read()).group(1).split()
        result[slug] = {'src': f'/platform-logos/{slug}.svg', 'aspect': round(float(vb[2]) / float(vb[3]), 3), 'bg': None}
        return
    im = Image.open(path).convert('RGBA')
    if slug in CIRCLE_ON_BLACK:
        from PIL import ImageDraw
        bright = im.convert('L').point(lambda v: 255 if v > 60 else 0)
        l, t, r, b = bright.getbbox()
        im = im.crop((l, t, r, b))
        m = Image.new('L', im.size, 0)
        ImageDraw.Draw(m).ellipse((1, 1, im.width - 2, im.height - 2), fill=255)
        im.putalpha(m)
    bg = None if slug in CIRCLE_ON_BLACK else is_filled(im)
    if not bg:
        im = trim(im)
        lf = light_fraction(im)
        if lf > 0.5:
            flags.append((slug, f'light pixels {lf:.0%} (may vanish on white)'))
    if max(im.size) > MAXD:
        s = MAXD / max(im.size)
        im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
    im.save(os.path.join(OUT, slug + '.webp'), 'WEBP', quality=92, method=6)
    result[slug] = {'src': f'/platform-logos/{slug}.webp', 'aspect': round(im.width / im.height, 3),
                    'bg': ('#%02x%02x%02x' % bg) if bg else None}


for slug, f in MAP.items():
    handle(slug, os.path.join(SRC, f))
for slug, p in EXTRA.items():
    handle(slug, p)

ts = "// Generated by scratch/process-logos.py — real platform logos (trimmed). `bg` = full-bleed colored logo.\n"
ts += "export interface PlatformLogo { src: string; aspect: number; bg: string | null }\n\n"
ts += "export const PLATFORM_LOGOS: Record<string, PlatformLogo> = " + json.dumps(dict(sorted(result.items())), indent=2) + "\n"
open(os.path.join(ROOT, 'src', 'data', 'platform-logos.ts'), 'w', encoding='utf-8').write(ts)

